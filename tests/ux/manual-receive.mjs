// UX62: manual receiving dialog (lot + expiry) on Products page.
import { chromium } from 'playwright';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.mjs': 'text/javascript', '.svg': 'image/svg+xml', '.json': 'application/json' };
const server = http.createServer((req, res) => {
  let p = decodeURIComponent(new URL(req.url, 'http://x').pathname);
  if (p === '/') p = '/index.html';
  const f = path.resolve(ROOT, '.' + p);
  if (!f.startsWith(ROOT + path.sep) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404).end('nf'); return; }
  res.writeHead(200, { 'content-type': TYPES[path.extname(f)] || 'application/octet-stream', 'cache-control': 'no-store' });
  fs.createReadStream(f).pipe(res);
});
await new Promise(r => server.listen(0, '127.0.0.1', r));
const BASE = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 }, locale: 'ar-EG' });
await ctx.route('**/*', r => { const m = r.request().method(), u = r.request().url(); if ((m !== 'GET' && m !== 'HEAD') || !(u.startsWith(BASE) || u.startsWith('data:') || u.startsWith('blob:'))) return r.abort(); return r.continue(); });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });
await page.addInitScript(() => { try { localStorage.setItem('nova-rx-language', 'ar'); } catch {} });
await page.goto(BASE + '/index.html', { waitUntil: 'load' });
await page.waitForSelector('#mainSearchInput');
let fail = 0;
const check = (ok, msg) => { console.log((ok ? 'PASS ' : 'FAIL ') + msg); if (!ok) fail++; };
await page.evaluate(() => document.querySelector('.nova-tab[data-page=products]').click());
await page.waitForSelector('#novaManualReceive');
const prod = await page.evaluate(() => window.NOVA_DEMO.products[0]);
const key = await page.evaluate(p => window.novaStock.keyOf(p), prod);
const before = await page.evaluate(k => window.novaStock.lots(k).length, key);
let clicks = 0;
await page.click('#novaManualReceive'); clicks++;
await page.fill('#novaRcvSearch', prod.barcode);
await page.waitForSelector('[data-rcv-pick]');
await page.click('[data-rcv-pick="0"]'); clicks++;
await page.fill('#novaRcvQty', '20');
await page.fill('#novaRcvLot', 'B2611');
await page.fill('#novaRcvExp', '2020-01');
await page.keyboard.press('Enter');
const errTxt = await page.locator('#novaRcvErr').innerText();
check(/[؀-ۿ]/.test(errTxt) && await page.locator('#novaManualRecv').count() === 1, 'past expiry: inline Arabic error, dialog stays: ' + errTxt);
check(await page.evaluate(k => window.novaStock.lots(k).length, key) === before, 'no stock change on rejection');
await page.fill('#novaRcvExp', '2027-03');
await page.click('#novaRcvOk'); clicks++;
check(await page.locator('#novaManualRecv').count() === 0, 'dialog closed on success');
check(clicks <= 4, `journey clicks = ${clicks} (<=4)`);
const lots = await page.evaluate(k => window.novaStock.lots(k), key);
check(JSON.stringify(lots).includes('B2611') && JSON.stringify(lots).includes('2027-03'), 'lots(key) contains B2611 2027-03: ' + JSON.stringify(lots));
const pick = await page.evaluate(k => window.novaStock.fefoPick(k, 5), key);
check(pick.ok && pick.picks.some(p => p.lot === 'B2611'), 'FEFO pick uses B2611');
const toast = await page.evaluate(() => document.getElementById('toastContainer').innerText);
check(/تم استلام 20/.test(toast) && /B2611/.test(toast) && /03\/2027/.test(toast), 'toast: ' + toast.trim());
await page.click('#novaManualReceive');
check(await page.locator('#novaManualRecv').count() === 1, 'dialog opens again');
await page.keyboard.press('Escape');
check(await page.locator('#novaManualRecv').count() === 0, 'Esc closes');
check(errors.length === 0, 'no console errors ' + errors.join('|'));
await browser.close(); server.close();
process.exit(fail ? 1 : 0);
