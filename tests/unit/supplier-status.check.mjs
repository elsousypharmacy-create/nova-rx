import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const S = createRequire(import.meta.url)('../../supplier-status.js');
assert.equal(S.classify({ state: 'off' }), 'missing_credential');
assert.equal(S.classify({ state: 'expired' }), 'auth_failed');
assert.equal(S.classify({ state: 'ok' }), 'connected');
assert.equal(S.classify({ state: 'ok' }, { state: 'ok' }), 'connected');
assert.equal(S.classify({ state: 'ok' }, { state: 'error', message: 'login failed 401' }), 'auth_failed');
assert.equal(S.classify({ state: 'ok' }, { state: 'error', message: 'timeout' }), 'down');
assert.equal(S.classify(null), 'unknown');
assert.equal(S.classify({ state: 'weird' }), 'unknown');
assert.equal(S.fromHttp(401), 'auth_failed'); assert.equal(S.fromHttp(500), 'down'); assert.equal(S.fromHttp(0), 'down');
const r = S.build([{ id: 'a', name: 'A', state: 'connected' }, { id: 'b', name: 'B', state: 'bogus' }], 't');
assert.equal(r.suppliers[1].state, 'unknown');
const sm = S.summarize(r.suppliers); assert.equal(sm.total, 2); assert.equal(sm.connected, 1); assert.equal(sm.unknown, 1);
assert.equal(S.isStale('2026-01-01T00:00:00Z', Date.parse('2026-01-01T01:00:00Z')), false);
assert.equal(S.isStale('2026-01-01T00:00:00Z', Date.parse('2026-01-01T02:00:00Z')), true);
assert.equal(S.isStale('nope'), true);
assert.ok(S.label('connected')); assert.ok(S.label('x'));
console.log('supplier-status OK');
